using System;

// This is our first C# program.
// The program demonstrates the basic structure of a C# application.

class HelloWorld
{
    // Main() is the entry point of a C# console application.
    // Program execution starts from the Main() method.

    static void Main()
    {
        // Console.WriteLine() prints text on the console.
        Console.WriteLine("Hello, World!");

        // We can also print our name.
        Console.WriteLine("My name is Adesh.");

        // Each statement in C# normally ends with a semicolon (;).
    }
}